        if x_c == 128:
            x = self.res1(x)
        elif x_c == 256:
            x = self.res2(x)
        elif x_c == 512:
            x = self.res3(x)

        x = x.permute(0, 2, 3, 1).contiguous()

        x = self.in_proj(x)
        x = F.silu(x)

        return x

